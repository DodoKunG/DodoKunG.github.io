const { chromium } = require('playwright');
const { pathToFileURL } = require('node:url');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({channel:'chrome',headless:true});
  try {
    const page = await browser.newPage({viewport:{width:390,height:844},acceptDownloads:true});
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.clock.install({time:new Date('2026-11-14T12:00:00Z')});
    await page.addInitScript(() => localStorage.setItem('lottery_wp_11_2569', JSON.stringify({text_m14a:'36',text_m14e:'35'})));
    await page.goto(process.env.WEEKLY_URL || pathToFileURL(require('node:path').resolve(__dirname, '..', 'index.html')).href);
    await page.waitForFunction(() => document.querySelectorAll('#weekly-body tr').length === 7);
    await page.locator('#weekly-end-date').focus();
    await page.evaluate(() => {
      const input = document.getElementById('weekly-end-date');
      input.value = '2026-11-13';
      window.dispatchEvent(new Event('focus'));
      input.dispatchEvent(new Event('change', {bubbles:true}));
    });
    assert.equal(await page.locator('#weekly-range').textContent(),'7/11/2569 – 13/11/2569');
    await page.evaluate(() => { document.getElementById('weekly-end-date').value = '2026-11-12'; });
    await page.locator('#weekly-apply-date').click();
    assert.equal(await page.locator('#weekly-range').textContent(),'6/11/2569 – 12/11/2569');
    await page.locator('#weekly-today').click();
    assert.equal(await page.locator('#weekly-drawn-count').textContent(),'0');
    const monthlyBefore = await page.locator('#lottery-main').innerHTML();
    const monthStorage = await page.evaluate(() => localStorage.getItem('lottery_wp_11_2569'));
    const morning = page.locator('[data-weekly-date="2026-11-14"][data-weekly-slot="morning"]');
    await morning.fill('7');
    await morning.blur();
    assert.equal(await page.locator('#weekly-drawn').textContent(),'07');
    assert.equal(await page.locator('#lottery-main').innerHTML(),monthlyBefore);
    assert.equal(await page.evaluate(() => localStorage.getItem('lottery_wp_11_2569')),monthStorage);
    await page.reload();
    assert.equal(await morning.textContent(),'7');
    const weeklyBefore = await page.evaluate(() => localStorage.getItem('lottery_weekly_v1'));
    await page.evaluate(() => {document.querySelector('[data-id="m14a"]').textContent='22';saveLottery();});
    assert.equal(await morning.textContent(),'7');
    assert.equal(await page.evaluate(() => localStorage.getItem('lottery_weekly_v1')),weeklyBefore);
    await page.evaluate(() => toggleTheme());
    assert.equal(await page.locator('#weekly-capture').evaluate(el => el.classList.contains('week-light')),false);
    await page.locator('#weekly-theme').click();
    assert.equal(await page.locator('#weekly-capture').evaluate(el => el.classList.contains('week-light')),true);
    const evening = page.locator('[data-weekly-date="2026-11-14"][data-weekly-slot="evening"]');
    await evening.fill('24'); await evening.blur();
    assert.equal(await page.locator('#weekly-drawn-count').textContent(),'2');
    await page.locator('#weekly-undo').click();
    assert.equal(await evening.textContent(),'');
    const monthlyAfter = await page.locator('#lottery-main').innerHTML();
    page.once('dialog', d => d.accept());
    await page.locator('#weekly-clear').click();
    assert.equal(await morning.textContent(),'');
    assert.equal(await page.locator('#lottery-main').innerHTML(),monthlyAfter);
    await page.locator('#weekly-undo').click();
    assert.equal(await morning.textContent(),'7');
    const monthlyBeforeDateChange = await page.locator('#lottery-main').innerHTML();
    await page.locator('#weekly-end-date').fill('2026-10-31');
    await page.locator('#weekly-end-date').dispatchEvent('change');
    assert.equal(await page.locator('#weekly-range').textContent(),'25/10/2569 – 31/10/2569');
    assert.equal(await page.locator('#weekly-drawn-count').textContent(),'0');
    const oldMorning = page.locator('[data-weekly-date="2026-10-31"][data-weekly-slot="morning"]');
    await oldMorning.fill('12'); await oldMorning.blur();
    await page.reload();
    assert.equal(await page.locator('#weekly-end-date').inputValue(),'2026-10-31');
    assert.equal(await oldMorning.textContent(),'12');
    page.once('dialog', d => d.accept());
    await page.locator('#weekly-clear').click();
    assert.equal(await oldMorning.textContent(),'');
    await page.locator('#weekly-undo').click();
    assert.equal(await oldMorning.textContent(),'12');
    await page.locator('#weekly-today').click();
    assert.equal(await morning.textContent(),'7');
    assert.equal(await page.locator('#weekly-drawn').textContent(),'07');
    assert.equal(await page.locator('#lottery-main').innerHTML(),monthlyBeforeDateChange);
    await morning.fill('หยุด'); await morning.blur();
    assert.equal(await morning.getAttribute('colspan'),'2');
    assert.equal(await evening.isVisible(),false);
    await page.locator('#weekly-capture').screenshot({path:require('node:path').join(require('node:os').tmpdir(), 'weekly-independent-mobile.png')});
    const downloading=page.waitForEvent('download');
    await page.locator('#weekly-download').click();
    const download=await downloading;
    assert.equal(fs.readFileSync(await download.path()).subarray(1,4).toString(),'PNG');
    assert.deepEqual(errors,[]);
    console.log('Browser checks passed: isolated tables, selected dates across months, persistence, return to today, range-scoped clear/undo, theme, holiday and PNG export.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
